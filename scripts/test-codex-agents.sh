#!/usr/bin/env bash
#
# test-codex-agents.sh — tests for bin/codex-agents-sync.
#
# Hermetic: HOME, CODEX_HOME and all three sources point into a temp sandbox, so the
# real ~/.codex/AGENTS.md and the private register are never read or written. The one
# test that reads this repo's real claude/*.md uses --print, which writes nothing.
#
# Run: ./scripts/test-codex-agents.sh [--verbose]   Exit: 0 all passed, 1 otherwise.
#
# shellcheck disable=SC2015 # `cond && pass || fail` is safe here: pass/fail always return 0

set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SYNC="$SCRIPT_DIR/../bin/codex-agents-sync"
VERBOSE=false
[ "${1:-}" = "--verbose" ] && VERBOSE=true

RED="\033[31m"; GREEN="\033[32m"; CYAN="\033[36m"; BOLD="\033[1m"; NC="\033[0m"
PASS_COUNT=0; FAIL_COUNT=0
pass() { PASS_COUNT=$((PASS_COUNT + 1)); echo -e "  ${GREEN}✓ PASS${NC}: $1"; }
fail() {
  FAIL_COUNT=$((FAIL_COUNT + 1)); echo -e "  ${RED}✗ FAIL${NC}: $1"
  if [ -s "$OUT" ]; then if $VERBOSE; then sed 's/^/      | /' "$OUT"; else sed 's/^/      | /' "$OUT" | head -20; fi; fi
}
header() { echo ""; echo -e "${BOLD}${CYAN}── $1 ──${NC}"; }

T="$(mktemp -d "${TMPDIR:-/tmp}/codex-agents-test.XXXXXX")"
T="$(cd "$T" && pwd -P)"
trap 'rm -rf "$T"' EXIT
OUT="$T/out"; : > "$OUT"
rc=0

reset_sandbox() {
  rm -rf "${T:?}/home" "${T:?}/src" "${T:?}/codex"
  mkdir -p "$T/home" "$T/src"
  printf '# Machine\n\nmachine-fact-one\n\n@~/somewhere/imported.md\n' > "$T/src/global.md"
  printf '# Workspace\n\nworkspace-rule-one\n\n@relative/import.md\n\nworkspace-rule-two\n' > "$T/src/dev.md"
  printf '# Register\n\nregister-entry-one\n' > "$T/src/register.md"
}

# run <args...> — the script with every path inside the sandbox. Sets rc, fills $OUT.
run() {
  HOME="$T/home" CODEX_HOME="$T/codex" DEV_ROOT="$T/dev" \
    CODEX_SYNC_GLOBAL="$T/src/global.md" CODEX_SYNC_DEV="$T/src/dev.md" \
    CODEX_SYNC_REGISTER="$T/src/register.md" \
    bash "$SYNC" "$@" > "$OUT" 2>&1
  rc=$?
}
first_backup() { find "$T/codex" -name 'AGENTS.md.bak-*' 2>/dev/null | head -n 1; }
file_count() { find "$T/codex" -type f | wc -l | tr -d ' '; }
mode_of() { stat -f '%Lp' "$1" 2>/dev/null || stat -c '%a' "$1"; }
AG="$T/codex/AGENTS.md"

header "write"
reset_sandbox; run
[ "$rc" = 0 ] && [ -f "$AG" ] && pass "writes AGENTS.md into CODEX_HOME, exit 0" || fail "no file written (exit $rc)"
grep -q 'machine-fact-one' "$AG" && grep -q 'workspace-rule-one' "$AG" && grep -q 'workspace-rule-two' "$AG" \
  && grep -q 'register-entry-one' "$AG" && pass "holds all three sources" || fail "a source is missing from the build"
[ "$(grep -n 'machine-fact-one' "$AG" | cut -d: -f1)" -lt "$(grep -n 'workspace-rule-one' "$AG" | cut -d: -f1)" ] \
  && [ "$(grep -n 'workspace-rule-one' "$AG" | cut -d: -f1)" -lt "$(grep -n 'register-entry-one' "$AG" | cut -d: -f1)" ] \
  && pass "order is machine, workspace, register" || fail "sources are out of order"
! grep -q '^@' "$AG" && pass "import lines are dropped" || fail "an @ import line survived"
head -n 1 "$AG" | grep -q 'Generated by dotfiles/bin/codex-agents-sync' && pass "first line marks the file as generated" || fail "no generated marker"
[ "$(mode_of "$AG")" = "600" ] && pass "mode 600" || fail "mode is $(mode_of "$AG"), want 600"
[ ! -e "$T/home/.codex" ] && pass "nothing written outside CODEX_HOME" || fail "wrote under HOME"
[ -z "$(first_backup)" ] && pass "no backup on a first write" || fail "made a backup with no earlier file"

header "idempotent"
before="$(cksum < "$AG")"; run
[ "$rc" = 0 ] && grep -q 'up to date' "$OUT" && [ "$(cksum < "$AG")" = "$before" ] && pass "second run changes nothing" || fail "second run rewrote the file"
[ "$(file_count)" = 1 ] && pass "second run leaves one file" || fail "stray files in CODEX_HOME"

header "--check"
run --check
[ "$rc" = 0 ] && pass "--check passes after a write" || fail "--check failed after a write (exit $rc)"
printf 'workspace-rule-three\n' >> "$T/src/dev.md"; before="$(cksum < "$AG")"; run --check
[ "$rc" = 1 ] && grep -q 'differs' "$OUT" && pass "--check exits 1 when a source changed" || fail "--check missed drift (exit $rc)"
[ "$(cksum < "$AG")" = "$before" ] && pass "--check writes nothing" || fail "--check modified the file"
printf 'register-entry-two\n' >> "$T/src/register.md"; run; run --check
[ "$rc" = 0 ] && grep -q 'register-entry-two' "$AG" && pass "a register change is picked up by the next write" || fail "register change not written"
rm -f "$AG"; run --check
[ "$rc" = 1 ] && grep -q 'missing' "$OUT" && [ ! -e "$AG" ] && pass "--check exits 1 on a missing file and does not create it" || fail "--check on a missing file (exit $rc)"

header "--print"
reset_sandbox; run --print
[ "$rc" = 0 ] && grep -q 'workspace-rule-one' "$OUT" && [ ! -e "$T/codex" ] && pass "--print shows the build and writes nothing" || fail "--print wrote or printed nothing"

header "hand-written file"
reset_sandbox; mkdir -p "$T/codex"; printf 'old hand-written rules\n' > "$AG"; run
bak="$(first_backup)"
[ "$rc" = 0 ] && [ -n "$bak" ] && grep -q 'old hand-written rules' "$bak" && pass "a hand-written file is kept as a dated backup" || fail "hand-written file lost (exit $rc)"
grep -q 'workspace-rule-one' "$AG" && pass "and replaced by the build" || fail "build not written over the hand-written file"
printf 'edited by hand again\n' > "$AG"; run
[ "$rc" = 1 ] && grep -q 'edited by hand again' "$AG" && pass "a second hand-written file is not overwritten while the backup exists" || fail "overwrote a hand-written file (exit $rc)"

header "limits and errors"
reset_sandbox; run; before="$(cksum < "$AG")"
CODEX_SYNC_MAX_BYTES=50; export CODEX_SYNC_MAX_BYTES; printf 'more\n' >> "$T/src/dev.md"; run; unset CODEX_SYNC_MAX_BYTES
[ "$rc" = 1 ] && grep -q 'over the 50 byte limit' "$OUT" && [ "$(cksum < "$AG")" = "$before" ] && pass "a build over the byte limit is refused, the old file stays" || fail "oversize build (exit $rc)"
reset_sandbox; rm -f "$T/src/register.md"; run
[ "$rc" = 0 ] && grep -q 'Ask before modifying any repo' "$AG" && grep -q 'register not found' "$OUT" && pass "no register: builds with the ask-first notice and says so" || fail "missing register (exit $rc)"
reset_sandbox; rm -f "$T/src/global.md"; run
[ "$rc" = 2 ] && [ ! -e "$AG" ] && pass "a missing source is exit 2, nothing written" || fail "missing source (exit $rc)"
reset_sandbox; run --bogus
[ "$rc" = 2 ] && [ ! -e "$AG" ] && pass "an unknown argument is exit 2" || fail "unknown argument (exit $rc)"
run --help
[ "$rc" = 0 ] && grep -q 'codex-agents-sync --check' "$OUT" && pass "--help prints the header" || fail "--help (exit $rc)"

header "this repo's sources"
HOME="$T/home" CODEX_HOME="$T/codex-real" DEV_ROOT="$T/dev" bash "$SYNC" --print > "$OUT" 2>&1; rc=$?
size="$(wc -c < "$OUT" | tr -d ' ')"
[ "$rc" = 0 ] && [ "$size" -lt 26000 ] && pass "claude/CLAUDE.md + claude/dev-CLAUDE.md build to $size bytes, leaving room for the register under 32768" \
  || fail "real sources build to $size bytes (exit $rc)"
! grep -q '^@' "$OUT" && pass "no import line left in the real build" || fail "an @ import survived in the real build"
[ ! -e "$T/codex-real" ] && pass "the real-source check wrote nothing" || fail "--print wrote a file"

echo ""
echo -e "${BOLD}codex-agents-sync: $PASS_COUNT passed, $FAIL_COUNT failed${NC}"
[ "$FAIL_COUNT" = 0 ]
